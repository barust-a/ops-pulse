const pluralRules = new Intl.PluralRules('fr-FR');

interface PluralForms {
  readonly one: string;
  readonly other: string;
}

function plural(count: number, forms: PluralForms): string {
  const form = pluralRules.select(count) === 'one' ? forms.one : forms.other;
  return form.replace('{count}', new Intl.NumberFormat('fr-FR').format(count));
}

